"""The human approval gate, and the extract command that runs approved configs.

The reviewer sees a one-page packet: what the agent thinks the source is, every
mapping with its holdout coverage and error rate, the final test the model never
saw, warnings about silent drops and identifier/name disagreement, what was left
unmapped and why, what the agent changed in each revise round, and raw -> canonical
previews of records outside the model's sample.
"""

import datetime as dt
import hashlib
import json
from collections import Counter

import yaml

from . import CONFIGS, OUTPUTS, ROOT, engine
from .inspect_tools import download

REVIEW_DIR = OUTPUTS / "review"


def load_config(slug):
    return yaml.safe_load((CONFIGS / f"{slug}.yaml").read_text(encoding="utf-8"))


def save_config(slug, cfg):
    # Rewrite the YAML but keep the "#" comment lines at the top of the file ("generated by the
    # onboarding agent, not written by hand"), which a plain YAML dump would lose.
    path = CONFIGS / f"{slug}.yaml"
    header = "".join(l for l in path.read_text(encoding="utf-8").splitlines(keepends=True) if l.startswith("#"))
    path.write_text(header + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, width=110), encoding="utf-8")


def is_approved(cfg):
    """Approved by a reviewer, and unchanged since. Every stage that consumes a config uses this."""
    rv = cfg.get("review") or {}
    return rv.get("status") == "approved" and rv.get("approved_config_hash") == engine.config_hash(cfg)


def _fmt_src(s):
    return " + ".join(s) if isinstance(s, list) else str(s)


def write_packet(slug, cfg, report, run):
    # Builds outputs/review/<slug>.md as a list of Markdown lines (L) and joins them at the end.
    # Everything shown comes from the config, the validation report and the saved run state, so
    # the reviewer reads exactly what the agent produced and measured.
    insp = run.get("inspect") or {}
    rounds = run.get("rounds") or []
    emp = (report or {}).get("empirical") or {}
    stats = {p["index"]: p for p in emp.get("per_mapping", [])}
    n_hold = emp.get("holdout_records", 0)
    src, ar = cfg["source"], cfg["agent_run"]
    final = run.get("validation_final")
    final_line = "not run (the run predates it, or the file is too small to spare rows)" if not final else (
        f"{'PASSED' if final['passed'] else 'FAILED, needs attention'} on "
        f"{(final.get('empirical') or {}).get('holdout_records', 0)} records the model never saw")
    warnings = list(dict.fromkeys((report.get("warnings") or []) + ((final or {}).get("warnings") or [])))
    L = [
        f"# Review: {src['title']}",
        "",
        f"- **Publisher:** {src['publisher']}",
        f"- **Licence:** {src['licence']}" + (f" ⚠ {src['licence_flag']}" if src.get("licence_flag") else ""),
        f"- **Resource:** {src['resource_url']}",
        f"- **Agent says it is:** {insp.get('what_it_is')}",
        f"- **Record grain:** {insp.get('record_grain')}",
        f"- **Contains business entities:** {insp.get('contains_business_entities')} ({insp.get('evidence')})",
        f"- **Reader:** `{json.dumps(cfg['reader'])}`",
        f"- **Record id:** `{json.dumps(cfg.get('record_id'))}`",
        f"- **Source reliability (agent's proposal):** {(cfg.get('source_reliability') or {}).get('value')} "
        f"({(cfg.get('source_reliability') or {}).get('rationale')})",
        f"- **Validation on {n_hold} held-out records (used while revising):** "
        f"{'PASSED' if report.get('passed') else 'FAILED, needs attention'}",
        f"- **Final test:** {final_line}",
        f"- **Agent cost:** {ar['llm_calls']} calls, {ar['input_tokens']} in / {ar['output_tokens']} out tokens, "
        f"${ar['usd']}, {ar['wall_seconds']}s, {ar['revise_rounds']} revise round(s)",
        "",
    ]
    if warnings:
        L += ["**Validator warnings (passing does not prove these values are true):**", ""] + [
            f"- {w}" for w in warnings] + [""]
    if insp.get("concerns"):
        L += ["**Agent's concerns:**", ""] + [f"- {c}" for c in insp["concerns"]] + [""]
    L += ["## Mappings", "",
          "| canonical | source | transforms | conf | holdout coverage | error rate | rationale |",
          "|---|---|---|---|---|---|---|"]
    for i, m in enumerate(cfg.get("mappings") or []):
        st = stats.get(i, {})
        tr = ", ".join(t if isinstance(t, str) else t.get("op") for t in m.get("transforms") or []) or "-"
        src_txt = f"const `{m['constant']}`" if "constant" in m else f"`{_fmt_src(m.get('source'))}`"
        cov = f"{st.get('records_with_value', '?')}/{n_hold}"
        L.append(f"| {m['canonical']} | {src_txt} | {tr} | {m.get('confidence')} | {cov} | "
                 f"{st.get('error_rate', '?')} | {(m.get('rationale') or '').replace('|', '/')} |")
    for title, key, k in (("Unmapped source fields", "unmapped_source_fields", "source"),
                          ("Canonical fields left empty", "unmapped_canonical_fields", "canonical")):
        items = cfg.get(key) or []
        L += ["", f"## {title} ({len(items)})", ""] + [f"- `{x.get(k)}`: {x.get('reason')}" for x in items]
    if cfg.get("relationships"):
        L += ["", "## Relationship hints", ""] + [
            f"- `{r.get('source')}` ({r.get('kind')}): {r.get('note')}" for r in cfg["relationships"]]
    if report.get("failing") or report.get("structural_issues"):
        L += ["", "## Still failing", "", "```", json.dumps(
            {"structural": report.get("structural_issues"), "failing": report.get("failing")}, indent=1)[:4000], "```"]
    L += ["", "## What the agent changed while revising", ""]
    for r in rounds:
        L.append(f"- Round from v{r['from_version']} (passed before: {r['passed_before']}): "
                 + ("no changes, signed off" if r["no_changes"] else ""))
        L += [f"  - {c.get('what')}: {c.get('why')}" for c in r["changes"]]
    L += ["", "## Preview: held-out records, raw → canonical", ""]
    for j, p in enumerate(emp.get("preview", [])[:5]):
        L.append(f"**Record {j + 1}**")
        L.append("")
        for field, v in p.items():
            out = v.get("error") and f"ERROR {v['error']}" or v.get("values")
            L.append(f"- {field}: `{str(v.get('raw'))[:80]}` → `{out}`")
        L.append("")
    if cfg.get("notes"):
        L += ["## Agent notes", ""] + [f"- {n}" for n in cfg["notes"]]
    L += ["", "---", f"Approve: `python -m firmable review {slug} --approve --reviewer <name>`  ",
          f"Reject: `python -m firmable review {slug} --reject --note \"why\"`  ",
          f"Send back with feedback: `python -m firmable review {slug} --feedback \"what to change\"`"]
    REVIEW_DIR.mkdir(parents=True, exist_ok=True)
    (REVIEW_DIR / f"{slug}.md").write_text("\n".join(L) + "\n", encoding="utf-8")


def review(slug, approve=False, reject=False, feedback=None, reviewer=None, note=None):
    """The human gate. Three outcomes: approve (later stages may use the config), reject (they may
    not), or feedback (the config goes back to the agent with the reviewer's words)."""
    packet = REVIEW_DIR / f"{slug}.md"
    # With no flag given, run interactively: print the packet and ask.
    if not (approve or reject or feedback):
        print(packet.read_text(encoding="utf-8"))
        choice = input("\n[a]pprove / [r]eject / [f]eedback / [q]uit: ").strip().lower()
        if choice.startswith("a"):
            approve, reviewer = True, reviewer or input("reviewer name: ").strip()
            note = note or input("note (optional): ").strip() or None
        elif choice.startswith("r"):
            reject, note = True, input("why: ").strip()
        elif choice.startswith("f"):
            feedback = input("feedback for the agent: ").strip()
        else:
            return
    cfg = load_config(slug)
    # Feedback does not edit the config here. It re-runs the agent's revise step with the feedback
    # in the prompt, so the agent still writes every line of the config, never the reviewer.
    if feedback:
        from .agent import human_feedback
        if not human_feedback(slug, feedback):
            raise SystemExit(f"the agent could not finish revising {slug}; see data/runs/{slug}/state.json")
        print(f"agent revised the config; re-review: python -m firmable review {slug}")
        return
    if approve and not reviewer:
        raise SystemExit("--reviewer is required to approve")
    if approve and cfg.get("review", {}).get("status") == "pending_needs_attention" and not note:
        raise SystemExit("this config failed validation; approving it needs a --note saying why it is acceptable")
    # Approval records who, when, and the hash of the config as it stood at that moment. If
    # anyone edits a mapping afterwards the hash no longer matches and is_approved() turns false.
    cfg["review"] = {
        "status": "approved" if approve else "rejected",
        "reviewer": reviewer,
        "at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "notes": note,
        "approved_config_hash": engine.config_hash(cfg) if approve else None,
    }
    save_config(slug, cfg)
    print(f"{slug}: {cfg['review']['status']}")


def file_sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def raw_status(cfg):
    """(path, drift record). Hashes the file itself, so a changed file cannot hide behind stale
    metadata. Public resources change: a fresh download often differs from what was approved."""
    src = cfg["source"]
    path, meta = download(src["resource_url"], src["resource_id"])
    actual = file_sha256(path)
    drifted = actual != src.get("raw_sha256")
    if drifted:
        print(f"  WARNING: {src['dataset_name']}: this file differs from the one the config was approved "
              f"against. Counts will differ from the committed outputs. Re-onboard before trusting them.")
    return path, {"raw_sha256": actual, "approved_raw_sha256": src.get("raw_sha256"), "source_drifted": drifted,
                  "truncated_download": bool(meta.get("truncated"))}


def raw_path(cfg):
    return raw_status(cfg)[0]


def extract(slugs=None, limit=1000, allow_unapproved=False):
    """Run each approved config through the engine over the first `limit` records. Writes two files
    per source: <slug>.jsonl (one observation per line) and <slug>.stats.json (counts per field,
    errors per field with examples, the extractor version, and whether the raw file has changed)."""
    out_dir = OUTPUTS / "observations"
    out_dir.mkdir(parents=True, exist_ok=True)
    slugs = slugs or sorted(p.stem for p in CONFIGS.glob("*.yaml"))
    for slug in slugs:
        cfg = load_config(slug)
        status = (cfg.get("review") or {}).get("status")
        if status != "approved" and not allow_unapproved:
            print(f"{slug}: skipped (review status {status!r})")
            continue
        if status == "approved" and cfg["review"].get("approved_config_hash") != engine.config_hash(cfg):
            print(f"{slug}: skipped, config edited after approval")
            continue
        path, raw = raw_status(cfg)
        obs, stats = engine.run(cfg, path, limit=limit)
        with open(out_dir / f"{slug}.jsonl", "w", encoding="utf-8") as f:
            for o in obs:
                f.write(json.dumps(o, ensure_ascii=False) + "\n")
        errs = Counter(e["canonical"] for e in stats["errors"])
        summary = {"slug": slug, "source_id": cfg["source_id"], "review_status": status,
                   "records": stats["records"],
                   "observations": stats["observations"],
                   "observations_by_field": dict(Counter(o["field"] for o in obs)),
                   "errors_by_field": dict(errs),
                   "error_examples": stats["errors"][:20],
                   "extractor_version": engine.extractor_version(cfg),
                   **raw}
        (out_dir / f"{slug}.stats.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"{slug}: {stats['records']} records -> {stats['observations']} observations, "
              f"{sum(errs.values())} field errors")
